-- =========================================================================
-- تعديل فهرس كود الوحدة للسماح بتسجيل أكثر من عميل/شريك لنفس الوحدة
-- =========================================================================
-- الوضع الحالي: يحتوي جدول clients على قيد UNIQUE باسم unique_eoi على عمود eoi_number
-- مما يمنع إضافة أكثر من عميل بنفس الوحدة في قاعدة البيانات.
--
-- هذا الملف يسقط قيد الـ UNIQUE ويستبدله بفهرس عادي (Non-Unique INDEX) 
-- يغطي كود الوحدة والمشروع معاً لضمان سرعة البحث ومطابقة المشاريع.
-- =========================================================================

-- 1. إسقاط قيد الفريد (UNIQUE) عن كود الوحدة
ALTER TABLE clients DROP INDEX unique_eoi;

-- 2. إنشاء فهرس مركب عادي على كود الوحدة والمشروع لتحقيق أعلى سرعة استعلام
ALTER TABLE clients ADD INDEX idx_eoi_project (eoi_number, project);

